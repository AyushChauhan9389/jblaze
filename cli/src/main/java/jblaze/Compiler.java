package jblaze;

import java.io.ByteArrayOutputStream;
import java.io.OutputStream;
import java.io.StringWriter;
import java.net.URI;
import java.nio.charset.StandardCharsets;
import java.nio.file.Path;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;

import javax.tools.FileObject;
import javax.tools.ForwardingJavaFileManager;
import javax.tools.JavaCompiler;
import javax.tools.JavaFileObject;
import javax.tools.JavaFileObject.Kind;
import javax.tools.SimpleJavaFileObject;
import javax.tools.StandardJavaFileManager;
import javax.tools.ToolProvider;

/**
 * In-process javac that keeps its file manager (and the JIT) warm and returns bytecode in memory. Sources
 * generated by annotation processors go to the {@code -s} directory in the options, like Gradle's build.
 */
final class Compiler {

	record Result(Map<String, byte[]> classes, String errors) {
		boolean ok() {
			return errors == null;
		}
	}

	private final JavaCompiler javac = ToolProvider.getSystemJavaCompiler();

	private final StandardJavaFileManager files = javac.getStandardFileManager(null, null, StandardCharsets.UTF_8);

	private final List<String> options;

	Compiler(List<String> options) {
		this.options = options;
	}

	synchronized Result compile(List<Path> sources) {
		Map<String, ByteArrayOutputStream> out = new LinkedHashMap<>();
		var fm = new ForwardingJavaFileManager<>(files) {
			@Override
			public JavaFileObject getJavaFileForOutput(Location location, String className, Kind kind,
					FileObject sibling) throws java.io.IOException {
				if (kind != Kind.CLASS) {
					return super.getJavaFileForOutput(location, className, kind, sibling); // generated sources
				}
				var bytes = new ByteArrayOutputStream();
				out.put(className, bytes);
				return new SimpleJavaFileObject(URI.create("mem:///" + className.replace('.', '/') + kind.extension),
						kind) {
					@Override
					public OutputStream openOutputStream() {
						return bytes;
					}
				};
			}
		};
		var diagnostics = new StringWriter();
		boolean ok = javac.getTask(diagnostics, fm, null, options, null, files.getJavaFileObjectsFromPaths(sources))
			.call();
		if (!ok) {
			return new Result(Map.of(), diagnostics.toString());
		}
		Map<String, byte[]> classes = new LinkedHashMap<>();
		out.forEach((name, bytes) -> classes.put(name, bytes.toByteArray()));
		return new Result(classes, null);
	}

}
